import { getMessagesForLocale } from '@/i18n/messages';
import { site } from '@/lib/site';

function documentText(lines: string[]): string {
  return `${lines.join('\n').trim()}\n`;
}

export function buildLlmsTxt(): string {
  return documentText([
    `# ${site.name}`,
    '',
    `> ${site.description}`,
    '',
    'Garmin Personal API MCP is an independent open-source project. It is not affiliated with or endorsed by Garmin.',
    '',
    '## Key facts',
    '',
    `- Package: ${site.packageName}`,
    `- Current version: ${site.version}`,
    `- MCP server ID: ${site.mcpServerId}`,
    `- Runtime: Node.js 22 or newer on macOS, Windows, or Linux`,
    `- Deployment model: local process only; no hosted MCP endpoint or remote relay`,
    `- Access: ${site.toolCount} read-only tools backed by Garmin Personal API GET operations`,
    '- Credentials: stored in user-only files on the computer running the MCP process',
    '- Privacy boundary: tool results are returned to the selected AI client and may be processed under that provider\'s privacy policy',
    '',
    '## Primary pages',
    '',
    `- [English homepage](${site.origin}/): Product overview, setup, supported data, privacy, and FAQ`,
    `- [简体中文首页](${site.origin}/zh): 中文产品说明、接入步骤、数据范围、隐私与常见问题`,
    `- [Full AI-readable context](${site.llmsFull}): Detailed project facts, setup, capabilities, and limitations`,
    '',
    '## Authoritative sources',
    '',
    `- [Source code](${site.github})`,
    `- [npm package](${site.npm})`,
    `- [Agent setup contract](${site.agentInstructions})`,
    `- [Security policy](${site.security})`,
    `- [Garmin Personal API](${site.garminPersonalApi})`,
    `- [Model Context Protocol](${site.mcp})`,
  ]);
}

export function buildLlmsFullTxt(): string {
  const en = getMessagesForLocale('en');
  const zh = getMessagesForLocale('zh');
  const dataSections = en.data.topics.flatMap((topic) => [
    `### ${topic.title}`,
    '',
    topic.body,
    '',
  ]);
  const capabilitySections = en.capabilities.groups.flatMap((group) => [
    `### ${group.title}`,
    '',
    group.description,
    `Representative tools: ${group.tools.join(', ')}.`,
    '',
  ]);
  const privacyItems = en.privacy.boundaries.map(([title, description]) => `- **${title}:** ${description}`);
  const faqItems = en.faq.items.flatMap((item) => [`### ${item.question}`, '', item.answer, '']);
  const chineseFacts = zh.projectFacts.items.map((item) => `- **${item.label}：**${item.value}`);

  return documentText([
    `# ${site.name}: complete project context`,
    '',
    `> ${site.description}`,
    '',
    'This document is the canonical machine-readable summary of the public website. Prefer the linked repository, npm package, Garmin documentation, and visible website content when verifying a claim.',
    '',
    '## Identity',
    '',
    `- Canonical website: ${site.origin}/`,
    `- Chinese website: ${site.origin}/zh`,
    `- npm package: ${site.packageName}`,
    `- Version: ${site.version}`,
    `- MCP server ID: ${site.mcpServerId}`,
    `- Publisher: ${site.publisher} contributors`,
    '- License: MIT',
    '- Implementation: TypeScript on Node.js 22 or newer',
    '- Supported operating systems: macOS, Windows, and Linux',
    '',
    '## What the project does',
    '',
    en.projectFacts.items.map((item) => `- **${item.label}:** ${item.value}`).join('\n'),
    '',
    'A compatible AI client launches the package as a local Model Context Protocol process. The process validates bounded requests, calls the Garmin Personal API directly over HTTPS, and returns structured results to that client. The project does not operate a hosted MCP service, account system, database, Docker service, or cloud relay.',
    '',
    '## Recommended setup',
    '',
    'Send this exact request to a capable local AI client:',
    '',
    '```text',
    site.setupPrompt,
    '```',
    '',
    'The client should follow AGENTS.md, run the localized local authorization flow, register the package under the MCP server ID `trainingloadai`, run the doctor command, and verify the registration. The user must paste the Garmin Personal API key only into the temporary page served on 127.0.0.1, never into an AI conversation.',
    '',
    'Manual authorization and diagnostics:',
    '',
    '```bash',
    `npx -y ${site.packageName} auth --locale en`,
    `npx -y ${site.packageName} doctor`,
    '```',
    '',
    'The MCP process command is:',
    '',
    '```text',
    `npx -y ${site.packageName}`,
    '```',
    '',
    '## Capabilities',
    '',
    ...capabilitySections,
    '## Garmin Personal API data coverage',
    '',
    ...dataSections,
    '## Privacy and security boundary',
    '',
    ...privacyItems,
    '',
    '- Tool results are returned to the MCP host and AI model selected by the user. Their privacy terms apply, so “local MCP” does not mean every result remains on-device.',
    '- The service is not a medical device and does not provide medical diagnosis.',
    '- The project is not affiliated with or endorsed by Garmin. Garmin and Garmin Connect are trademarks of Garmin Ltd. or its subsidiaries.',
    '',
    '## Frequently asked questions',
    '',
    ...faqItems,
    '## 中文摘要',
    '',
    zh.projectFacts.description,
    '',
    ...chineseFacts,
    '',
    '接入指令：',
    '',
    '```text',
    site.setupPrompt,
    '```',
    '',
    'Garmin Personal API Key 只应输入本机临时授权页，不要发送到聊天中。工具结果会返回用户选择的 AI 客户端，并可能由对应模型处理。',
    '',
    '## Authoritative sources',
    '',
    `- Website: ${site.origin}/`,
    `- Chinese website: ${site.origin}/zh`,
    `- Source code: ${site.github}`,
    `- npm package: ${site.npm}`,
    `- Setup contract: ${site.agentInstructions}`,
    `- Security policy: ${site.security}`,
    `- License: ${site.license}`,
    `- Garmin Personal API: ${site.garminPersonalApi}`,
    `- Model Context Protocol: ${site.mcp}`,
  ]);
}
